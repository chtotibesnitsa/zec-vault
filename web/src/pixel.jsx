function rects(rows, ch) {
  const out = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) if (r[x] === ch) out.push(<rect key={`${ch}${x}-${y}`} x={x} y={y} width="1.02" height="1.02" />);
  });
  return out;
}

export function Px({ name, size = 28, className = '' }) {
  const fr = ICONS[name];
  if (!fr) return null;
  return (
    <svg viewBox="0 0 9 9" width={size} height={size} className={`px ${className}`} shapeRendering="crispEdges" aria-hidden="true">
      <g className="px-a">
        <g className="px-ink">{rects(fr[0], '#')}</g>
        <g className="px-acc">{rects(fr[0], '+')}</g>
      </g>
      <g className="px-b">
        <g className="px-ink">{rects(fr[1], '#')}</g>
        <g className="px-acc">{rects(fr[1], '+')}</g>
      </g>
    </svg>
  );
}
