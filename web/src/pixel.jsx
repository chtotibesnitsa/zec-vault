export function Px({ name, size = 28, className = '', pixel = false }) {
  if (!pixel && LINE[name]) {
    return (
      <svg viewBox="0 0 24 24" width={size} height={size} className={`ic ${className}`} fill="none" stroke="currentColor" strokeWidth="1.7" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
        {LINE[name]}
      </svg>
    );
  }
  const fr = ICONS[name];
  if (!fr) return null;
  return (
    <svg viewBox="0 0 9 9" width={size} height={size} className={`px ${className}`} shapeRendering="crispEdges" aria-hidden="true">
      <g className="px-a">
        <g className="px-ink">{rects(fr[0], '#')}</g>
        <g className="px-acc">{rects(fr[0], '+')}</g>
      </g>
      <g className="px-b">
        <g className="px-ink">{rects(fr[1], '#')}</g>
        <g className="px-acc">{rects(fr[1], '+')}</g>
      </g>
    </svg>
  );
}
